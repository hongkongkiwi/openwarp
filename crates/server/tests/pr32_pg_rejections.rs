static SEQ: AtomicU32 = AtomicU32::new(0);
static SERIAL: tokio::sync::Mutex<()> = tokio::sync::Mutex::const_new(());
const MASTER: [u8;32] = [83;32];
const ENV_KEY: [u8;32] = [84;32];
const SESSION: &str = "pr32-disposable-postgres-owner";
const PASSWORD: &str = "pr32-disposable-management-password";
fn ident(name: &str) -> String { format!("\"{}\"",name.replace('"',"\"\"")) }
async fn connect(config: &tokio_postgres::Config) -> tokio_postgres::Client {
    let (client, connection) = config.connect(tokio_postgres::NoTls).await.expect("connect owned private PostgreSQL fixture");
    tokio::spawn(async move { let _ = connection.await; }); client
}
struct Roles { admin: tokio_postgres::Client, manager: String, url: String }
impl Roles {
    async fn new() -> Self {
        let url = std::env::var("OPENWARP_TEST_LEASE_PG").expect("qualification requires OPENWARP_TEST_LEASE_PG for the owned private 127.0.0.1:54289 PostgreSQL fixture");
        let config: tokio_postgres::Config = url.parse().expect("private PostgreSQL URL");
        assert_eq!(config.get_hosts(), &[tokio_postgres::config::Host::Tcp("127.0.0.1".into())],"refusing any host except the owned literal loopback fixture");
        assert!(config.get_hostaddrs().is_empty()); assert_eq!(config.get_ports(), &[54289],"refusing existing or external PostgreSQL services");
        assert_eq!(config.get_user(),Some("lease_test_admin"),"use only the owned fixture administrator");
        assert_eq!(config.get_ssl_mode(),tokio_postgres::config::SslMode::Disable,"local fixture must explicitly disable TLS");
        let admin = connect(&config).await;
        let manager = format!("ow_pr32_{}_{}",std::process::id(),SEQ.fetch_add(1,Ordering::SeqCst));
        admin.batch_execute(&format!("CREATE ROLE {} LOGIN CREATEROLE PASSWORD '{}'",ident(&manager),PASSWORD)).await.expect("create only this case's management role");
        let mut manager_url = reqwest::Url::parse(&url).unwrap(); manager_url.set_username(&manager).unwrap(); manager_url.set_password(Some(PASSWORD)).unwrap();
        let manager_config: tokio_postgres::Config = manager_url.as_str().parse().unwrap();
        let manager_client = connect(&manager_config).await;
        let row = manager_client.query_one("SELECT current_user,rolcreaterole FROM pg_roles WHERE rolname=current_user",&[]).await.unwrap();
        assert_eq!(row.get::<_,String>(0),manager); assert!(row.get::<_,bool>(1),"initial management role must be able to create leases");
        Self { admin, manager, url: manager_url.to_string() }
    }
    async fn permit(&self, permit: bool) {
        self.admin.batch_execute(&format!("ALTER ROLE {} {}",ident(&self.manager),if permit { "CREATEROLE" } else { "NOCREATEROLE" })).await.unwrap();
    }
    async fn validity(&self, target: &str) -> Option<i64> {
        self.admin.query_opt("SELECT EXTRACT(EPOCH FROM rolvaliduntil)::bigint FROM pg_roles WHERE rolname=$1",&[&target]).await.unwrap().map(|row| row.get(0))
    }
    async fn assert_permission_denied(&self, target: &str, renew: bool) {
        let config: tokio_postgres::Config = self.url.parse().unwrap(); let client = connect(&config).await;
        let sql = if renew { format!("ALTER ROLE {} VALID UNTIL '2040-01-01 00:00:00+00'",ident(target)) } else { format!("DROP ROLE {}",ident(target)) };
        let error = client.execute(&sql,&[]).await.expect_err("the private database must definitely reject the management role's statement");
        assert_eq!(error.code(),Some(&tokio_postgres::error::SqlState::INSUFFICIENT_PRIVILEGE),"fixture must receive PostgreSQL SQLSTATE 42501, not a timeout or transport error");
    }
    async fn cleanup(&self, target: &str) {
        self.admin.batch_execute(&format!("DROP ROLE IF EXISTS {}; DROP ROLE {}",ident(target),ident(&self.manager))).await.expect("remove only roles generated by this case");
    }
}

struct Server { child: Child, dir: PathBuf, db: Db, base: String, client: Client }
impl Drop for Server { fn drop(&mut self) { let _ = self.child.kill(); let _ = self.child.wait(); let _ = std::fs::remove_dir_all(&self.dir); } }
struct Reply { status: u16, body: Value }
impl Server {
    async fn start() -> Self {
        let dir = std::env::temp_dir().join(format!("openwarp-pr32-pg-{}-{}",std::process::id(),SEQ.fetch_add(1,Ordering::SeqCst)));
        std::fs::create_dir(&dir).unwrap(); let url = format!("sqlite://{}/test.db",dir.display());
        let db = Db::open(&url).await.unwrap(); seed_epoch(&db,&MASTER).await.unwrap();
        db.exec("INSERT INTO orgs(id,name,created_at) VALUES(?,?,?)",&[json!("org"),json!("PostgreSQL rejection fixture"),json!(now())]).await.unwrap();
        db.exec("INSERT INTO users(id,email,pass_hash,pubkey,wrapped_privkey,created_at,email_verified) VALUES(?,?,?,?,?,?,?)",&[json!("owner"),json!("owner@pr32.test.invalid"),json!("unused"),json!("unused"),json!("unused"),json!(now()),json!(1)]).await.unwrap();
        db.exec("INSERT INTO org_members(org_id,user_id,role) VALUES(?,?,?)",&[json!("org"),json!("owner"),json!("owner")]).await.unwrap();
        db.exec("INSERT INTO sessions(token_hash,user_id,created_at) VALUES(?,?,?)",&[json!(oc::hash_token(SESSION)),json!("owner"),json!(now())]).await.unwrap();
        db.exec("INSERT INTO apps(id,org_id,name,created_at) VALUES(?,?,?,?)",&[json!("app"),json!("org"),json!("PostgreSQL rejection fixture"),json!(now())]).await.unwrap();
        db.exec("INSERT INTO envs(id,app_id,name,env_key_wrapped,mode,created_at) VALUES(?,?,?,?,?,?)",&[json!("env"),json!("app"),json!("test"),json!(oc::encrypt_symmetric(&MASTER,&ENV_KEY)),json!("sse"),json!(now())]).await.unwrap();
        let reserved = std::net::TcpListener::bind("127.0.0.1:0").unwrap(); let addr = reserved.local_addr().unwrap(); let base = format!("http://{addr}");
        let mut command = Command::new(env!("CARGO_BIN_EXE_openwarp-server"));
        command.env_clear().env("DATABASE_URL",url).env("ADDR",addr.to_string()).env("OPENWARP_PUBLIC_URL",&base)
            .env("OPENWARP_MASTER_KEY",oc::b64(&MASTER)).env("OPENWARP_ENV","test").env("OPENWARP_ALLOWED_DB_HOSTS","127.0.0.1:54289").env("TOKIO_WORKER_THREADS","1");
        drop(reserved); let child = command.stdout(Stdio::null()).stderr(Stdio::null()).spawn().expect("start private API child");
        let client = Client::builder().no_proxy().timeout(Duration::from_secs(15)).build().unwrap();
        let mut s = Self { child, dir, db, base, client }; let deadline = Instant::now()+Duration::from_secs(30);
        loop {
            assert!(s.child.try_wait().unwrap().is_none(),"private API server exited before health");
            if let Ok(r) = s.client.get(format!("{}/health",s.base)).send().await { if r.status().is_success() { break; } }
            assert!(Instant::now()<deadline,"private API server readiness timeout"); tokio::time::sleep(Duration::from_millis(50)).await;
        }
        s
    }
    async fn call(&self, method: Method, path: &str, body: Option<Value>) -> Reply {
        let mut r = self.client.request(method,format!("{}{}",self.base,path)).bearer_auth(SESSION);
        if let Some(body) = body { r = r.json(&body); }
        let r = r.send().await.expect("private API request completes"); let status = r.status().as_u16();
        Reply { status, body: r.json().await.expect("API JSON response") }
    }
    async fn issue(&self, roles: &Roles) -> (String,String) {
        let reply = self.call(Method::POST,"/api/envs/env/dynamic",Some(json!({"name":"definite-rejection","type":"postgres","ttl_secs":3600,"config":{"connection":roles.url}}))).await;
        assert_eq!(reply.status,200,"private management role must issue a real PostgreSQL lease");
        (reply.body["id"].as_str().expect("lease id").to_string(),reply.body["username"].as_str().expect("created role name").to_string())
    }
    async fn action(&self, lid: &str, renew: bool) -> Reply {
        if renew { self.call(Method::POST,&format!("/api/leases/{lid}/renew"),Some(json!({"ttl_secs":7200}))).await }
        else { self.call(Method::DELETE,&format!("/api/leases/{lid}"),None).await }
    }
    async fn metadata(&self, lid: &str) -> Value { let reply = self.call(Method::GET,&format!("/api/leases/{lid}"),None).await; assert_eq!(reply.status,200); reply.body }
    async fn assert_no_claim(&self, lid: &str) {
        assert!(self.db.one("SELECT name FROM instance_leases WHERE name=?",&[json!(format!("lease-op:{lid}"))]).await.unwrap().is_none(),"a definitive PostgreSQL rejection must release its operation claim without operator reconciliation");
    }
}

async fn api_rejection_case(renew: bool) {
    let roles = Arc::new(Roles::new().await); let server = Server::start().await; let (lid,target) = server.issue(&roles).await;
    let cleanup_target = target.clone(); let worker = roles.clone();
    // Catch assertion failures so a red qualification still cleans up its own database roles.
    let local = tokio::task::LocalSet::new();
    let outcome = local.run_until(async move { tokio::task::spawn_local(async move {
        let before = server.metadata(&lid).await; let original = worker.validity(&target).await.expect("issued role exists");
        assert_eq!(before["expires_at"].as_i64(),Some(original)); assert_eq!(before["renewable"],true);
        worker.permit(false).await; worker.assert_permission_denied(&target,renew).await;
        assert_eq!(worker.validity(&target).await,Some(original),"the definite-rejection fixture must have no remote side effect");
        let rejected = server.action(&lid,renew).await;
        assert!((400..600).contains(&rejected.status),"permission rejection cannot report success"); assert!(rejected.body["error"].is_string());
        assert_eq!(worker.validity(&target).await,Some(original),"rejected ALTER/DROP must leave the real PostgreSQL role unchanged");
        let after = server.metadata(&lid).await; assert_eq!(after["expires_at"],before["expires_at"]); assert_eq!(after["revoked"],false);
        server.assert_no_claim(&lid).await; assert_eq!(after["renewable"],true,"definite rejection is retryable, not an unresolved remote operation");
        worker.permit(true).await;
        let retry = server.action(&lid,renew).await; assert_eq!(retry.status,200,"restoring permission must allow API retry without manual claim deletion");
        server.assert_no_claim(&lid).await; let after_retry = server.metadata(&lid).await;
        if renew {
            let actual = worker.validity(&target).await.expect("renewal keeps the same role");
            assert!(actual>original,"successful retry must extend real PostgreSQL validity"); assert_eq!(after_retry["expires_at"].as_i64(),Some(actual)); assert_eq!(after_retry["revoked"],false);
        } else {
            assert_eq!(worker.validity(&target).await,None,"successful retry must actually drop the role"); assert_eq!(after_retry["revoked"],true);
        }
    }).await }).await;
    roles.cleanup(&cleanup_target).await;
    if let Err(error) = outcome { std::panic::resume_unwind(error.into_panic()); }
}

#[tokio::test]
async fn definite_postgres_alter_rejection_releases_api_claim_and_retry_succeeds() { let _serial = SERIAL.lock().await; api_rejection_case(true).await; }
#[tokio::test]
async fn definite_postgres_drop_rejection_releases_api_claim_and_retry_succeeds() { let _serial = SERIAL.lock().await; api_rejection_case(false).await; }

#[tokio::test]
async fn public_postgres_outcomes_distinguish_server_rejection_from_uncertain_dispatch() {
    let _serial = SERIAL.lock().await;
    let roles = Arc::new(Roles::new().await); let target = format!("{}_target",roles.manager);
    pglease::create_role(&roles.url,&target,"pr32-disposable-child-password",now()+3600).await.expect("create role positive control");
    let cleanup_target = target.clone(); let worker = roles.clone();
    let outcome = tokio::spawn(async move {
        let original = worker.validity(&target).await.unwrap(); worker.permit(false).await;
        worker.assert_permission_denied(&target,true).await; worker.assert_permission_denied(&target,false).await;
        let renewal = pglease::renew_role(&worker.url,&target,now()+7200).await;
        let revocation = pglease::drop_role_with_outcome(&worker.url,&target).await;
        assert!(renewal.is_err() && revocation.is_err(),"known PostgreSQL rejections must remain errors");
        assert_eq!(worker.validity(&target).await,Some(original),"server-rejected ALTER and DROP have no side effect");
        assert!(!matches!(renewal,Err(pglease::RenewError::Uncertain)),"PostgreSQL acknowledged ALTER rejection must not be classified as an uncertain dispatch");
        assert!(!matches!(revocation,Err(pglease::RenewError::Uncertain)),"PostgreSQL acknowledged DROP rejection must not be classified as an uncertain dispatch");
        worker.permit(true).await;
        assert!(pglease::renew_role(&worker.url,&target,now()+7200).await.is_ok(),"permitted renewal succeeds");
        assert!(pglease::drop_role_with_outcome(&worker.url,&target).await.is_ok(),"permitted revocation succeeds");
        assert_eq!(worker.validity(&target).await,None);
        let socket = std::net::TcpListener::bind("127.0.0.1:0").unwrap(); let port = socket.local_addr().unwrap().port(); drop(socket);
        let mut refused = reqwest::Url::parse(&worker.url).unwrap(); refused.set_port(Some(port)).unwrap();
        assert!(matches!(pglease::renew_role(refused.as_str(),&target,now()+7200).await,Err(pglease::RenewError::NotSent)),"pre-connection refusal remains known not sent");
        assert!(matches!(pglease::drop_role_with_outcome(refused.as_str(),&target).await,Err(pglease::RenewError::NotSent)),"pre-connection DROP refusal remains known not sent");
    }).await;
    roles.cleanup(&cleanup_target).await;
    if let Err(error) = outcome { std::panic::resume_unwind(error.into_panic()); }
}
